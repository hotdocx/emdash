export const CORE_CATEGORICAL_USABILITY_GRADUATION_PROPOSAL =
    deepFreeze(rawProposal);

const bindingFor = (
    target: string
) => LAMBDAPI_V32_CATEGORICAL_SURFACE_BINDINGS.find(
    binding => binding.target === target
);

const applicationFor = (
    target: string
) => CORE_CATEGORICAL_SURFACE_SPECIFICATION.applications.find(
    application => application.target === target
);

const currentApplicationPartition = () => {
    const qualified = new Set<string>(
        CORE_CATEGORICAL_DEPENDENT_PREREQUISITES.map(
            prerequisite => prerequisite.id
        )
    );
    const partition = {
        eligibleOrQualified: [] as string[],
        reservedNaturality: [] as string[],
        activeButUntransferred: [] as string[],
        inactiveAuthority: [] as string[],
        totalApplicationJudgments:
            CORE_CATEGORICAL_SURFACE_SPECIFICATION.applications.length
    };

    for (
        const application of
            CORE_CATEGORICAL_SURFACE_SPECIFICATION.applications
    ) {
        const postTransferQualified =
            qualified.has(application.target) &&
            application.implementationStatus ===
                'active-kernel-untransferred' &&
            application.surfaceDisposition ===
                'requires-usability-2a';
        if (
            application.surfaceDisposition === 'eligible' ||
            postTransferQualified
        ) {
            partition.eligibleOrQualified.push(application.target);
        } else if (
            application.surfaceDisposition ===
                'requires-naturality-gate'
        ) {
            partition.reservedNaturality.push(application.target);
        } else if (
            application.surfaceDisposition ===
                'unsupported-authority-gap'
        ) {
            partition.inactiveAuthority.push(application.target);
        } else {
            partition.activeButUntransferred.push(application.target);
        }
    }

    return partition;
};

export function validateCoreCategoricalUsabilityGraduationProposal(
    proposal: CoreCategoricalUsabilityGraduationProposalInput =
        CORE_CATEGORICAL_USABILITY_GRADUATION_PROPOSAL
): void {
    if (
        CORE_CATEGORICAL_PROGRAM_REVISION !==
            proposal.validation.programRevision ||
        CORE_CATEGORICAL_STRUCTURAL_PREREQUISITES.length !==
            proposal.implementedEnvelope.structuralPrerequisiteCount ||
        CORE_CATEGORICAL_DEPENDENT_PREREQUISITES.length !==
            proposal.implementedEnvelope
                .transferredDisplayedPrerequisiteCount
    ) {
        throw new CoreCategoricalUsabilityGraduationProposalError(
            'GRADUATION_IMPLEMENTATION_DRIFT',
            'Categorical frontend implementation no longer matches the ' +
                'graduation evidence envelope'
        );
    }

    if (
        !sameData(
            CORE_CATEGORICAL_SURFACE_SPECIFICATION.contextualIr,
            proposal.contextualIr
        ) ||
        !sameData(
            currentApplicationPartition(),
            proposal.surfaceApplicationPartition
        )
    ) {
        throw new CoreCategoricalUsabilityGraduationProposalError(
            'GRADUATION_IMPLEMENTATION_DRIFT',
            'Categorical contextual IR or complete application partition ' +
                'no longer matches the graduation evidence envelope'
        );
    }

    for (const entry of proposal.activeButUntransferred) {
        const application = applicationFor(entry.target);
        const binding = bindingFor(entry.target);
        if (
            application?.implementationStatus !==
                'active-kernel-untransferred' ||
            binding?.serializedName !== entry.authorityName ||
            binding.authority === 'explicitly-deferred-symbol'
        ) {
            throw new CoreCategoricalUsabilityGraduationProposalError(
                'GRADUATION_OWNER_BOUNDARY_DRIFT',
                `Active-untransferred boundary '${entry.target}' drifted`
            );
        }
    }

    const laxity = proposal.authorityGaps[0];
    const laxityApplication = applicationFor(laxity.target);
    const laxityBinding = bindingFor(laxity.target);
    if (
        laxityApplication?.implementationStatus !== 'not-active' ||
        laxityBinding?.serializedName !== laxity.authorityName ||
        laxityBinding.authority !== 'explicitly-deferred-symbol'
    ) {
        throw new CoreCategoricalUsabilityGraduationProposalError(
            'GRADUATION_OWNER_BOUNDARY_DRIFT',
            'Deliberately inactive displayed laxity boundary drifted'
        );
    }

    if (
        proposal.status !==
            'proposal-awaiting-h-dttlf-usability-graduate' ||
        proposal.reviewGate !== 'H-DTTLF-USABILITY-GRADUATE' ||
        proposal.decisionId !== 'D-DTTLF-USABILITY-002' ||
        proposal.recommendation.authorityAuthorized !== false ||
        proposal.trustBoundary.productionLambdapiDependency !== false ||
        proposal.nextWorkPolicy
            .graduationApprovalResumesBulkTransferAutomatically !== false
    ) {
        throw new CoreCategoricalUsabilityGraduationProposalError(
            'GRADUATION_RECOMMENDATION_DRIFT',
            'Graduation proposal exceeds or weakens its review boundary'
        );
    }

    if (!sameData(proposal, rawProposal)) {
        throw new CoreCategoricalUsabilityGraduationProposalError(
            'GRADUATION_RECOMMENDATION_DRIFT',
            'Categorical usability graduation proposal differs from the ' +
                'exact pending recommendation'
        );
    }
}

validateCoreCategoricalUsabilityGraduationProposal();
